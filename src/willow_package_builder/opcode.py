# ruff: noqa: D102, N802
from typing import Protocol


class Opcode(int):
    """Opcode type."""


class Opcodes(Protocol):
    """Game-specific script opcode values."""

    # Variable access.
    @property
    def LOCAL_VARIABLE(self) -> Opcode: ...
    @property
    def INSTANCE_VARIABLE(self) -> Opcode: ...
    @property
    def DEFAULT_VARIABLE(self) -> Opcode: ...
    @property
    def SWITCH_SIZE(self) -> Opcode: ...
    @property
    def NATIVE_PARAMETER(self) -> Opcode: ...
    @property
    def BOOL_VARIABLE(self) -> Opcode: ...
    @property
    def STRUCT_MEMBER(self) -> Opcode: ...
    @property
    def OUT_VARIABLE(self) -> Opcode: ...

    # Optimized local access.
    @property
    def LOCAL_VARIABLE_INT(self) -> Opcode: ...
    @property
    def LOCAL_VARIABLE_FLOAT(self) -> Opcode: ...
    @property
    def LOCAL_VARIABLE_BYTE(self) -> Opcode: ...
    @property
    def LOCAL_VARIABLE_BOOL(self) -> Opcode: ...
    @property
    def LOCAL_VARIABLE_OBJECT(self) -> Opcode: ...

    # Assignment.
    @property
    def LET(self) -> Opcode: ...
    @property
    def LET_BOOL(self) -> Opcode: ...
    @property
    def LET_DELEGATE(self) -> Opcode: ...

    # Control flow.
    @property
    def RETURN(self) -> Opcode: ...
    @property
    def SWITCH(self) -> Opcode: ...
    @property
    def JUMP(self) -> Opcode: ...
    @property
    def JUMP_IF_NOT(self) -> Opcode: ...
    @property
    def STOP(self) -> Opcode: ...
    @property
    def ASSERT(self) -> Opcode: ...
    @property
    def CASE(self) -> Opcode: ...
    @property
    def NOTHING(self) -> Opcode: ...
    @property
    def LABEL_TABLE(self) -> Opcode: ...
    @property
    def GOTO_LABEL(self) -> Opcode: ...
    @property
    def EAT_RETURN_VALUE(self) -> Opcode: ...
    @property
    def SKIP(self) -> Opcode: ...
    @property
    def RETURN_NOTHING(self) -> Opcode: ...
    @property
    def CONDITIONAL(self) -> Opcode: ...
    @property
    def END_OF_SCRIPT(self) -> Opcode: ...
    @property
    def FILTER_EDITOR_ONLY(self) -> Opcode: ...

    # Function calls and arguments.
    @property
    def END_PARAMETER_VALUE(self) -> Opcode: ...
    @property
    def END_FUNCTION_PARAMS(self) -> Opcode: ...
    @property
    def VIRTUAL_FUNCTION(self) -> Opcode: ...
    @property
    def FINAL_FUNCTION(self) -> Opcode: ...
    @property
    def GLOBAL_FUNCTION(self) -> Opcode: ...
    @property
    def DEFAULT_PARAMETER_VALUE(self) -> Opcode: ...
    @property
    def EMPTY_PARAMETER_VALUE(self) -> Opcode: ...

    # Context and object creation.
    @property
    def NEW(self) -> Opcode: ...
    @property
    def CLASS_CONTEXT(self) -> Opcode: ...
    @property
    def SELF(self) -> Opcode: ...
    @property
    def CONTEXT(self) -> Opcode: ...
    @property
    def INTERFACE_CONTEXT(self) -> Opcode: ...

    # Casts.
    @property
    def META_CLASS_CAST(self) -> Opcode: ...
    @property
    def DYNAMIC_CAST(self) -> Opcode: ...
    @property
    def PRIMITIVE_CAST(self) -> Opcode: ...
    @property
    def INTERFACE_CAST(self) -> Opcode: ...

    # Constants.
    @property
    def INT_CONST(self) -> Opcode: ...
    @property
    def FLOAT_CONST(self) -> Opcode: ...
    @property
    def STRING_CONST(self) -> Opcode: ...
    @property
    def OBJECT_CONST(self) -> Opcode: ...
    @property
    def NAME_CONST(self) -> Opcode: ...
    @property
    def ROTATOR_CONST(self) -> Opcode: ...
    @property
    def VECTOR_CONST(self) -> Opcode: ...
    @property
    def BYTE_CONST(self) -> Opcode: ...
    @property
    def INT_ZERO(self) -> Opcode: ...
    @property
    def INT_ONE(self) -> Opcode: ...
    @property
    def TRUE(self) -> Opcode: ...
    @property
    def FALSE(self) -> Opcode: ...
    @property
    def NO_OBJECT(self) -> Opcode: ...
    @property
    def INT_CONST_BYTE(self) -> Opcode: ...
    @property
    def UNICODE_STRING_CONST(self) -> Opcode: ...

    # Struct comparisons.
    @property
    def STRUCT_EQUAL(self) -> Opcode: ...
    @property
    def STRUCT_NOT_EQUAL(self) -> Opcode: ...

    # Fixed-size array access.
    @property
    def ARRAY_ELEMENT(self) -> Opcode: ...

    # Dynamic arrays.
    @property
    def DYNAMIC_ARRAY_ELEMENT(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_LENGTH(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_INSERT(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_REMOVE(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_FIND(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_FIND_STRUCT(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_ADD(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_ADD_ITEM(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_REMOVE_ITEM(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_INSERT_ITEM(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_ITERATOR(self) -> Opcode: ...
    @property
    def DYNAMIC_ARRAY_SORT(self) -> Opcode: ...

    # Iteration.
    @property
    def ITERATOR(self) -> Opcode: ...
    @property
    def ITERATOR_POP(self) -> Opcode: ...
    @property
    def ITERATOR_NEXT(self) -> Opcode: ...

    # Delegates.
    @property
    def DELEGATE_EQUAL(self) -> Opcode: ...
    @property
    def DELEGATE_NOT_EQUAL(self) -> Opcode: ...
    @property
    def DELEGATE_FUNCTION_EQUAL(self) -> Opcode: ...
    @property
    def DELEGATE_FUNCTION_NOT_EQUAL(self) -> Opcode: ...
    @property
    def EMPTY_DELEGATE(self) -> Opcode: ...
    @property
    def DELEGATE_FUNCTION(self) -> Opcode: ...
    @property
    def DELEGATE_PROPERTY(self) -> Opcode: ...
    @property
    def INSTANCE_DELEGATE(self) -> Opcode: ...

    # Debug information.
    @property
    def DEBUG_INFO(self) -> Opcode: ...

    # Gearbox attribute expressions.
    @property
    def ATTRIBUTE_VARIABLE(self) -> Opcode: ...
    @property
    def LET_ATTRIBUTE(self) -> Opcode: ...


